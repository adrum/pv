#!/usr/bin/env python3
"""Regenerate build/windows/pecl.lock and pecl-source.lock: the PECL extensions
pv adds on Windows.

    ./build/windows/update-pecl-lock.py

php.net's Windows builds carry only php-src's own extensions, while the other
platforms build pv's whole set with static-php-cli. The PECL ones are added
from php.net's own PECL Windows builds, at downloads.php.net. Those carry no
published checksum, so this pins one: for each extension and PHP line it takes
the newest stable release built for that line's compiler, downloads it, and
writes its sha256. package-php-windows.sh refuses any zip that no longer
matches.

There is no PECL Windows build for arm64, so builds for it compile the same
releases in-tree from their PECL source tarballs, which publish no checksum
either; pecl-source.lock pins those, for the extensions that build from
php.net's arm64 dependency set.

Run it to pick up new releases or a new PHP line, then read the diff before
committing it: a changed hash for an unchanged version is a republished file,
and wants an explanation.
"""

from __future__ import annotations

import hashlib
import re
import sys
import urllib.request
from pathlib import Path

BASE = "https://downloads.php.net/~windows/pecl/releases"

# The compiler php.net builds each line with: a DLL from another one refuses
# to load.
LINES = {"7.4": "vc15", "8.0": "vs16", "8.1": "vs16", "8.2": "vs16", "8.3": "vs16", "8.4": "vs17", "8.5": "vs17"}

# The PECL extensions the other platforms build. uuid is not here: it wraps
# libuuid, and there is no Windows build of it.
EXTENSIONS = ["apcu", "igbinary", "msgpack", "redis", "mongodb", "yaml", "ssh2", "imagick"]

# Built in-tree on arm64. yaml and imagick are not: php.net's arm64
# dependency set has neither libyaml nor ImageMagick.
SOURCE_EXTENSIONS = ["apcu", "igbinary", "msgpack", "redis", "mongodb", "ssh2"]
PECL_SOURCES = "https://pecl.php.net/get"

ARCH = "x64"
LOCK = Path(__file__).with_name("pecl.lock")
SOURCE_LOCK = Path(__file__).with_name("pecl-source.lock")
SOURCE_HEADER = """\
# PECL source releases built in-tree into pv's Windows arm64 builds, for which
# PECL publishes no Windows build, from https://pecl.php.net/get/, which
# publishes no checksums. The releases pecl.lock pins for x64, each line
# building the one pinned for it there:
#
#   <extension> <version> <sha256 of the tarball>
#
# Generated by build/windows/update-pecl-lock.py; review the diff of any
# regeneration.
"""
HEADER = """\
# PECL extensions added to pv's Windows builds, from php.net's PECL Windows
# builds (https://downloads.php.net/~windows/pecl/releases/), which publish no
# checksums. Pinned here instead, one zip per extension, PHP line, compiler
# and architecture:
#
#   <extension> <version> <php-line> <compiler> <arch> <sha256 of the zip>
#
# Generated by build/windows/update-pecl-lock.py; review the diff of any
# regeneration. A line with no entry for an extension does not get it.
"""


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=120) as response:
        return response.read()


def version_key(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split("."))


def main() -> int:
    rows = []
    for extension in EXTENSIONS:
        listing = fetch(f"{BASE}/{extension}/").decode("utf-8", "replace")
        stable = sorted(
            {v for v in re.findall(r'href="(\d[^"/]*)/"', listing) if re.fullmatch(r"\d+\.\d+\.\d+", v)},
            key=version_key,
            reverse=True,
        )
        releases: dict[str, str] = {}
        for line, compiler in LINES.items():
            for version in stable[:12]:
                if version not in releases:
                    releases[version] = fetch(f"{BASE}/{extension}/{version}/").decode("utf-8", "replace")
                name = f"php_{extension}-{version}-{line}-nts-{compiler}-{ARCH}.zip"
                if name in releases[version]:
                    digest = hashlib.sha256(fetch(f"{BASE}/{extension}/{version}/{name}")).hexdigest()
                    rows.append(f"{extension} {version} {line} {compiler} {ARCH} {digest}")
                    print(f"{extension} {version} for {line}", file=sys.stderr)
                    break
            else:
                print(f"note: no {extension} build for PHP {line} ({compiler} {ARCH})", file=sys.stderr)
    LOCK.write_text(HEADER + "".join(f"{row}\n" for row in rows), newline="\n")
    print(f"wrote {LOCK}: {len(rows)} entries", file=sys.stderr)

    # Every release pinned for any line, for each extension built in-tree:
    # an arm64 build takes the one its line's x64 entry names.
    pinned: dict[str, set[str]] = {}
    for row in rows:
        extension, version = row.split()[:2]
        if extension in SOURCE_EXTENSIONS:
            pinned.setdefault(extension, set()).add(version)
    sources = []
    for extension in SOURCE_EXTENSIONS:
        for version in sorted(pinned[extension], key=version_key, reverse=True):
            digest = hashlib.sha256(fetch(f"{PECL_SOURCES}/{extension}-{version}.tgz")).hexdigest()
            sources.append(f"{extension} {version} {digest}")
    SOURCE_LOCK.write_text(SOURCE_HEADER + "".join(f"{row}\n" for row in sources), newline="\n")
    print(f"wrote {SOURCE_LOCK}: {len(sources)} entries", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
