// Generate the pages that would otherwise drift.
//
// The extension list and the platform matrix are facts about the build
// scripts, not prose. Documentation that claims an extension a wave does not
// ship is worse than no documentation, so these pages are derived from
// build/build-php.sh and .github/workflows/build-php.yml rather than
// hand-maintained. Edit those; this file follows.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const out = join(here, '..', 'src', 'content', 'docs', 'reference');

const buildScript = readFileSync(join(repo, 'build', 'build-php.sh'), 'utf8');
const workflow = readFileSync(
  join(repo, '.github', 'workflows', 'build-php.yml'),
  'utf8',
);

function extract(pattern, source, what) {
  const match = source.match(pattern);
  if (!match) {
    throw new Error(
      `could not find ${what} — the build scripts changed shape, so this ` +
        `generator needs updating rather than the docs being written by hand`,
    );
  }
  return match[1];
}

const extensions = extract(
  /^DEFAULT_EXTENSIONS="([^"]+)"/m,
  buildScript,
  'DEFAULT_EXTENSIONS in build/build-php.sh',
)
  .split(',')
  .map((name) => name.trim())
  .filter(Boolean);

const shared = extract(
  /^SHARED_EXTENSIONS="\$\{PHP_SHARED_EXTENSIONS:-([^}]+)\}"/m,
  buildScript,
  'SHARED_EXTENSIONS in build/build-php.sh',
).split(',');

const lines = extract(
  /description: 'PHP lines to build, comma-separated'\s*\n\s*default: '([^']+)'/,
  workflow,
  'the default PHP lines in build-php.yml',
).split(',');

const platforms = extract(
  /description: 'Platforms to build, comma-separated'\s*\n\s*default: '([^']+)'/,
  workflow,
  'the default platforms in build-php.yml',
).split(',');

// Per-line removals, so the page can say which lines lack what and why.
const strips = {};
for (const [, line, body] of buildScript.matchAll(
  /^ {4}(7\.4|8\.0)\)\n([\s\S]*?)^ {8};;/gm,
)) {
  strips[line] = [...body.matchAll(/strip_ext (\S+)/g)].map((m) => m[1]);
}

const runners = Object.fromEntries(
  [...workflow.matchAll(/"([a-z0-9_]+-[a-z0-9_]+)": "([^"]+)"/g)].map((m) => [
    m[1],
    m[2],
  ]),
);

const banner = `---
title: TITLE
description: DESCRIPTION
---

{/* Generated by docs/scripts/generate.mjs — edit the build scripts, not this file. */}
`;

mkdirSync(out, { recursive: true });

writeFileSync(
  join(out, 'extensions.mdx'),
  banner
    .replace('TITLE', 'Extensions')
    .replace(
      'DESCRIPTION',
      'What every pv PHP build includes, and what it deliberately does not.',
    ) +
    `
Every build carries this set. It is the supported surface: a statically linked
PHP cannot \`dlopen\` arbitrary extensions, so **\`pecl install <anything>\` does
not work** against these builds.

<div style="columns: 3; font-family: var(--sl-font-mono); font-size: 0.9em">

${extensions.map((name) => `- ${name}`).join('\n')}

</div>

## Shared

${shared
  .map(
    (name) =>
      `- **${name}** — shipped as \`lib/${name}.so\`, because it cannot be linked statically. Loaded with \`xdebug.mode = off\`; set \`XDEBUG_MODE\` to enable it for a single invocation, which Xdebug honors over any ini value.`,
  )
  .join('\n')}

## Not included, deliberately

- **sqlsrv** — Microsoft's ODBC driver is dylib-only on macOS.
- **pcov** — shared-only, like Xdebug. Use \`xdebug.mode=coverage\`.

## Removed on older lines

Some extensions require a newer PHP than the line they would ship on, so they
are dropped rather than failing the build:

${Object.entries(strips)
  .map(([line, names]) => `- **PHP ${line}** — ${names.join(', ')}`)
  .join('\n')}

Verification diffs \`php -m\` against the requested list on every build, so a
silently dropped extension fails the build rather than reaching you.
`,
);

writeFileSync(
  join(out, 'platforms.mdx'),
  banner
    .replace('TITLE', 'Platforms')
    .replace('DESCRIPTION', 'What pv builds, and on what.') +
    `
Each wave builds every PHP line for every platform below, on a **native**
runner — cross-compiling PHP to another architecture is not practical, and
arm64 Linux in particular cannot be built from an amd64 host.

| Platform | Runner |
|---|---|
${platforms.map((p) => `| \`${p}\` | \`${runners[p] ?? '—'}\` |`).join('\n')}

Windows is not supported: a different toolchain entirely, and a separate
project phase.

## PHP lines

${lines.map((l) => `\`${l}\``).join(' · ')}

A single failing line fails soft, so one broken version does not block a wave,
and the run summary names what went unpublished.

## The glibc floor on Linux

Linux builds link **glibc** rather than static musl. Static musl has no
\`dlopen\`, which means no shared Xdebug — and Xdebug cannot be linked
statically either, so there is no static path to a PHP with a debugger.

The trade is a floor: the resulting \`php\` needs a glibc at least as new as the
build image's. The client itself has no such floor — \`pv\` is built against
musl and runs anywhere.
`,
);

console.log(
  `generated extensions.mdx (${extensions.length} extensions) and platforms.mdx ` +
    `(${platforms.length} platforms, ${lines.length} lines)`,
);
